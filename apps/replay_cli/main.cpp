namespace {

using namespace ft;

// --check thresholds. A log may loosen them with a comment line such as
//   # check: g_rms<=0.35 aoa_rms<=1.5
constexpr double kDefaultGRmsLimit = 0.15;    // G
constexpr double kDefaultAoaRmsLimit = 0.5;   // deg
constexpr double kMaxLatencyS = 0.25;         // estimator delay beyond this fails the check
// Estimators restart after a gap / teleport / pause; their warm-up is not "error".
constexpr double kSettleAfterResetS = 0.5;
constexpr double kMaxLagSearchS = 0.3;
constexpr double kLagStepS = 0.005;

int usage() {
  std::fprintf(stderr,
               "usage:\n"
               "  replay_cli <log.csv> [--check] [--json] [--gmode nz|total]\n"
               "  replay_cli --generate <level|turn|pullpush|dogfight> --duration <s> --out <file>\n"
               "             [--seed N] [--dirty] [--no-velocity] [--fps N]\n");
  return 2;
}

bool parseDouble(const char* s, double& out) {
  char* end = nullptr;
  out = std::strtod(s, &end);
  return end != s && *end == '\0' && std::isfinite(out);
}

// ---------------------------------------------------------------------------------------
// Generation

int generate(const std::string& scenarioArg, double duration, const std::string& outPath,
             std::uint32_t seed, bool dirty, bool noVelocity, double fps, const std::string& cmdLine) {
  SimulatedSourceOptions opt;
  if (scenarioArg == "level") opt.scenario = Scenario::LevelCruise;
  else if (scenarioArg == "turn") opt.scenario = Scenario::SustainedTurn;
  else if (scenarioArg == "pullpush") opt.scenario = Scenario::PullUpPushOver;
  else if (scenarioArg == "dogfight") opt.scenario = Scenario::DogfightMix;
  else {
    std::fprintf(stderr, "unknown scenario '%s'\n", scenarioArg.c_str());
    return 2;
  }
  if (duration < 2.0) {
    std::fprintf(stderr, "--duration must be >= 2 s\n");
    return 2;
  }
  opt.seed = seed;
  opt.frameRateHz = fps;
  opt.provideVelocity = !noVelocity;
  if (dirty) {
    opt.dirty.positionNoiseM = 0.02;
    opt.dirty.velocityNoiseMS = 0.05;
    opt.dirty.frameJitter = 0.35;
    opt.dirty.dropProbability = 0.03;
    opt.dirty.duplicateProbability = 0.02;
  }

  SimulatedSource sim(opt);
  std::vector<RawFlightSample> samples;
  std::vector<FlightState> truth;
  const double flight = duration - 1.0;  // last second: results screen (phase Ended)
  if (dirty) {
    // One of each glitch, spread over the flight.
    sim.generate(flight * 0.3, samples, &truth);
    sim.injectSpike();
    sim.generate(flight * 0.2, samples, &truth);
    sim.injectHitch(0.4);
    sim.generate(flight * 0.2, samples, &truth);
    sim.injectTeleport();
    sim.generate(flight * 0.3, samples, &truth);
  } else {
    sim.generate(flight, samples, &truth);
  }
  sim.endMission();
  sim.generate(1.0, samples, &truth);

  CsvRecorder rec;
  std::string err;
  if (!rec.open(outPath, &err)) {
    std::fprintf(stderr, "%s\n", err.c_str());
    return 2;
  }
  rec.writeComment("AC8 flight telemetry log (simulated, with ground truth)");
  rec.writeComment("generated by: " + cmdLine);
  if (dirty) {
    rec.writeComment("dirty: noise, frame jitter, drops, duplicates, 1 spike, 1 hitch, 1 teleport");
    rec.writeComment("check: g_rms<=0.35 aoa_rms<=1.5");
  }
  for (std::size_t i = 0; i < samples.size(); ++i)
    rec.write({samples[i], truth[i].trueNz, truth[i].trueAoaDeg});
  rec.close();
  std::printf("wrote %zu rows (%.1f s, %s) to %s\n", rec.rowsWritten(), duration,
              scenarioName(opt.scenario), outPath.c_str());
  return 0;
}

// ---------------------------------------------------------------------------------------
// Replay + error analysis

struct CheckLimits {
  double gRms = kDefaultGRmsLimit;
  double aoaRms = kDefaultAoaRmsLimit;
};

// Reads "# check: key<=value ..." directives from comment lines.
CheckLimits readCheckDirectives(const std::string& path) {
  CheckLimits limits;
  std::ifstream file(path);
  std::string line;
  while (std::getline(file, line)) {
    const std::size_t pos = line.find("check:");
    if (line.empty() || line[0] != '#' || pos == std::string::npos) continue;
    std::string_view rest = std::string_view(line).substr(pos + 6);
    while (!rest.empty()) {
      const std::size_t sp = rest.find_first_of(" \t\r");
      const std::string token(rest.substr(0, sp));
      rest = sp == std::string_view::npos ? std::string_view{} : rest.substr(sp + 1);
      const std::size_t le = token.find("<=");
      double v = 0.0;
      if (le == std::string::npos || !parseDouble(token.c_str() + le + 2, v)) continue;
      const std::string key = token.substr(0, le);
      if (key == "g_rms") limits.gRms = v;
      else if (key == "aoa_rms") limits.aoaRms = v;
    }
  }
  return limits;
}

struct Point {
  double t, estimate;
};
struct Series {
  std::vector<Point> est;                        // estimator output at accepted samples
  std::vector<std::pair<double, double>> truth;  // (t, true value), every distinct row
};

// Truth linearly interpolated at time t (series sorted by time).
double truthAt(const std::vector<std::pair<double, double>>& truth, double t) {
  auto it = std::lower_bound(truth.begin(), truth.end(), std::make_pair(t, -1e300));
  if (it == truth.begin()) return it->second;
  if (it == truth.end()) return truth.back().second;
  const auto& b = *it;
  const auto& a = *(it - 1);
  const double w = b.first > a.first ? (t - a.first) / (b.first - a.first) : 1.0;
  return a.second + (b.second - a.second) * w;
}

struct ErrorStats {
  std::size_t count = 0;
  double rms = 0.0, maxAbs = 0.0;     // estimate vs truth at the same instant
  double lagS = 0.0;                  // delay that best aligns estimate and truth
  double lagRms = 0.0, lagMaxAbs = 0.0;
};

ErrorStats errorAtLag(const Series& s, double lag) {
  ErrorStats e;
  double sumSq = 0.0;
  for (const Point& p : s.est) {
    const double err = p.estimate - truthAt(s.truth, p.t - lag);
    sumSq += err * err;
    e.maxAbs = std::max(e.maxAbs, std::abs(err));
  }
  e.count = s.est.size();
  e.rms = e.count ? std::sqrt(sumSq / static_cast<double>(e.count)) : 0.0;
  return e;
}

// Smoothing filters delay the estimate by design; report that delay separately from the
// error that remains once it is accounted for (the actual estimation quality).
ErrorStats analyze(const Series& s) {
  ErrorStats result = errorAtLag(s, 0.0);
  result.lagRms = result.rms;
  result.lagMaxAbs = result.maxAbs;
  for (double lag = kLagStepS; lag <= kMaxLagSearchS + 1e-9; lag += kLagStepS) {
    const ErrorStats e = errorAtLag(s, lag);
    if (e.rms < result.lagRms) {
      result.lagRms = e.rms;
      result.lagMaxAbs = e.maxAbs;
      result.lagS = lag;
    }
  }
  return result;
}

struct ReplayResult {
  std::size_t rows = 0;
  double logDurationS = 0.0;
  bool hasVelocity = false, hasTruthNz = false, hasTruthAoa = false;
  MetricsSnapshot snapshot;
  ErrorStats g, aoa;
};

ReplayResult replay(const std::vector<CsvRow>& rows, GMode gMode) {
  PipelineConfig cfg;
  cfg.gMode = gMode;
  TelemetryPipeline pipeline(cfg);

  ReplayResult r;
  r.rows = rows.size();
  if (!rows.empty()) r.logDurationS = rows.back().sample.t - rows.front().sample.t;

  Series gSeries, aoaSeries;
  double lastResetT = -1e300, lastCollectedT = -1e300;
  std::uint64_t resets = 0;
  MissionPhase prevPhase = MissionPhase::None;
  for (const CsvRow& row : rows) {
    const RawFlightSample& s = row.sample;
    r.hasVelocity |= s.velocity.has_value();
    r.hasTruthNz |= row.trueNz.has_value();
    r.hasTruthAoa |= row.trueAoaDeg.has_value();
    if (row.trueNz && (gSeries.truth.empty() || s.t > gSeries.truth.back().first))
      gSeries.truth.emplace_back(s.t, *row.trueNz);
    if (row.trueAoaDeg && (aoaSeries.truth.empty() || s.t > aoaSeries.truth.back().first))
      aoaSeries.truth.emplace_back(s.t, *row.trueAoaDeg);

    pipeline.push(s);
    const MetricsSnapshot snap = pipeline.snapshot();
    const std::uint64_t nowResets = snap.quality.resetsGap + snap.quality.resetsTeleport;
    if (nowResets != resets || (prevPhase == MissionPhase::Paused && s.phase != MissionPhase::Paused))
      lastResetT = s.t;
    resets = nowResets;
    prevPhase = s.phase;

    const FlightMetrics& m = snap.current;
    const bool fresh = m.valid && m.t == s.t && s.t > lastCollectedT &&
                       s.phase != MissionPhase::Paused && s.t - lastResetT >= kSettleAfterResetS;
    if (!fresh) continue;
    lastCollectedT = s.t;
    // In Total mode `g` is a magnitude; compare the body Nz component instead.
    if (row.trueNz) gSeries.est.push_back({s.t, gMode == GMode::Nz ? m.g : m.loadFactorBody.z});
    if (row.trueAoaDeg && m.aoaValid) aoaSeries.est.push_back({s.t, m.aoaDeg});
  }
  r.snapshot = pipeline.snapshot();
  if (!gSeries.est.empty()) r.g = analyze(gSeries);
  if (!aoaSeries.est.empty()) r.aoa = analyze(aoaSeries);
  return r;
}

const MissionStats& reportedStats(const ReplayResult& r) {
  return r.snapshot.lastReport ? r.snapshot.lastReport->stats : r.snapshot.mission;
}

void printText(const std::string& path, const ReplayResult& r) {
  const MissionStats& m = reportedStats(r);
  const DataQuality& q = r.snapshot.quality;
  std::printf("log      %s\n", path.c_str());
  std::printf("         %zu rows, %.2f s, velocity %s, truth %s\n", r.rows, r.logDurationS,
              r.hasVelocity ? "yes" : "no (from position)", r.hasTruthNz ? "yes" : "no");
  if (r.snapshot.lastReport)
    std::printf("mission  #%u%s, %.2f s flown\n", r.snapshot.lastReport->id,
                r.snapshot.lastReport->aborted ? " (aborted)" : "", m.durationS);
  else
    std::printf("mission  no completed mission (live stats), %.2f s flown\n", m.durationS);
  std::printf("  G      max %+.2f at %.1f s, min %+.2f at %.1f s\n", m.maxG, m.maxGAtS, m.minG,
              m.minGAtS);
  std::printf("  onset  max %+.1f G/s, min %+.1f G/s\n", m.maxOnset, m.minOnset);
  std::printf("  AoA    max %.1f deg, max speed %.0f m/s\n", m.maxAoaDeg, m.maxSpeed);
  std::printf("  high-G %d episodes, longest %.2f s, total %.2f s\n", m.highGEpisodes,
              m.longestHighGS, m.totalHighGS);
  std::printf("  time in G bins:");
  for (double s : m.timeInGBinS) std::printf(" %.1f", s);
  std::printf(" s\n");
  std::printf("quality  accepted %llu, rejected: non-finite %llu, time %llu, implausible %llu; "
              "resets: gap %llu, teleport %llu\n",
              static_cast<unsigned long long>(q.accepted),
              static_cast<unsigned long long>(q.rejectedNonFinite),
              static_cast<unsigned long long>(q.rejectedTime),
              static_cast<unsigned long long>(q.rejectedImplausible),
              static_cast<unsigned long long>(q.resetsGap),
              static_cast<unsigned long long>(q.resetsTeleport));
  auto err = [](const char* name, const char* unit, const ErrorStats& e) {
    std::printf("  %-4s   n=%zu  rms %.3f %s, max %.3f  |  aligned (lag %3.0f ms): rms %.3f, max %.3f\n",
                name, e.count, e.rms, unit, e.maxAbs, e.lagS * 1000.0, e.lagRms, e.lagMaxAbs);
  };
  if (r.hasTruthNz || r.hasTruthAoa) {
    std::printf("error vs truth (valid samples, %.1f s settle after resets)\n", kSettleAfterResetS);
    if (r.hasTruthNz) err("Nz", "G", r.g);
    if (r.hasTruthAoa) err("AoA", "deg", r.aoa);
  }
}

void printJson(const std::string& path, const ReplayResult& r, bool checked, bool pass) {
  const MissionStats& m = reportedStats(r);
  const DataQuality& q = r.snapshot.quality;
  auto err = [](const ErrorStats& e) {
    std::printf("{\"n\": %zu, \"rms\": %.6g, \"max\": %.6g, \"lag_s\": %.3f, \"aligned_rms\": %.6g, "
                "\"aligned_max\": %.6g}",
                e.count, e.rms, e.maxAbs, e.lagS, e.lagRms, e.lagMaxAbs);
  };
  std::string escaped;
  for (char c : path) {
    if (c == '"' || c == '\\') escaped += '\\';
    escaped += c;
  }
  std::printf("{\n  \"log\": \"%s\", \"rows\": %zu, \"duration_s\": %.3f, \"has_velocity\": %s,\n",
              escaped.c_str(), r.rows, r.logDurationS, r.hasVelocity ? "true" : "false");
  std::printf("  \"mission\": {\"completed\": %s, \"aborted\": %s, \"duration_s\": %.3f, "
              "\"max_g\": %.4f, \"max_g_at_s\": %.3f, \"min_g\": %.4f, \"min_g_at_s\": %.3f, "
              "\"max_onset\": %.4f, \"min_onset\": %.4f, \"max_aoa_deg\": %.4f, \"max_speed\": %.3f, "
              "\"high_g_episodes\": %d, \"longest_high_g_s\": %.3f, \"total_high_g_s\": %.3f},\n",
              r.snapshot.lastReport ? "true" : "false",
              r.snapshot.lastReport && r.snapshot.lastReport->aborted ? "true" : "false", m.durationS,
              m.maxG, m.maxGAtS, m.minG, m.minGAtS, m.maxOnset, m.minOnset, m.maxAoaDeg, m.maxSpeed,
              m.highGEpisodes, m.longestHighGS, m.totalHighGS);
  std::printf("  \"quality\": {\"accepted\": %llu, \"rejected_non_finite\": %llu, \"rejected_time\": %llu, "
              "\"rejected_implausible\": %llu, \"resets_gap\": %llu, \"resets_teleport\": %llu},\n",
              static_cast<unsigned long long>(q.accepted),
              static_cast<unsigned long long>(q.rejectedNonFinite),
              static_cast<unsigned long long>(q.rejectedTime),
              static_cast<unsigned long long>(q.rejectedImplausible),
              static_cast<unsigned long long>(q.resetsGap),
              static_cast<unsigned long long>(q.resetsTeleport));
  std::printf("  \"error_nz\": ");
  if (r.hasTruthNz) err(r.g); else std::printf("null");
  std::printf(",\n  \"error_aoa\": ");
  if (r.hasTruthAoa) err(r.aoa); else std::printf("null");
  std::printf(",\n  \"check\": %s\n}\n", checked ? (pass ? "\"pass\"" : "\"fail\"") : "null");
}

// Returns true if the replay meets the limits; explains failures on stderr.
bool runCheck(const ReplayResult& r, const CheckLimits& limits, bool quiet) {
  bool pass = true;
  auto fail = [&pass](const std::string& msg) {
    std::fprintf(stderr, "CHECK FAILED: %s\n", msg.c_str());
    pass = false;
  };
  auto checkSeries = [&](const char* name, const ErrorStats& e, double limit, const char* unit) {
    char buf[200];
    if (e.count == 0) {
      std::snprintf(buf, sizeof buf, "%s: no valid samples to compare", name);
      return fail(buf);
    }
    if (e.lagRms > limit) {
      std::snprintf(buf, sizeof buf, "%s rms error %.3f %s > %.3f", name, e.lagRms, unit, limit);
      fail(buf);
    }
    if (e.lagS > kMaxLatencyS) {
      std::snprintf(buf, sizeof buf, "%s latency %.0f ms > %.0f ms", name, e.lagS * 1000.0,
                    kMaxLatencyS * 1000.0);
      fail(buf);
    }
  };
  if (!r.snapshot.lastReport) fail("log produced no mission report");
  if (r.hasTruthNz) checkSeries("Nz", r.g, limits.gRms, "G");
  if (r.hasTruthAoa) checkSeries("AoA", r.aoa, limits.aoaRms, "deg");
  if (!quiet) {
    if (!r.hasTruthNz && !r.hasTruthAoa) std::printf("check    no ground truth in log, error check skipped\n");
    std::printf("check    %s (limits: Nz rms <= %.2f G, AoA rms <= %.2f deg, latency <= %.0f ms)\n",
                pass ? "PASS" : "FAIL", limits.gRms, limits.aoaRms, kMaxLatencyS * 1000.0);
  }
  return pass;
}

}  // namespace

int main(int argc, char** argv) {
  std::vector<std::string> args(argv + 1, argv + argc);
  std::string logPath, scenario, outPath, cmdLine = "replay_cli";
  bool check = false, json = false, dirty = false, noVelocity = false, gen = false;
  double duration = 0.0, fps = 60.0, seed = 1234.0;
  GMode gMode = GMode::Nz;
  for (const std::string& a : args) cmdLine += " " + a;

  for (std::size_t i = 0; i < args.size(); ++i) {
    const std::string& a = args[i];
    auto value = [&](double& out) {
      return i + 1 < args.size() && parseDouble(args[++i].c_str(), out);
    };
    if (a == "--check") check = true;
    else if (a == "--json") json = true;
    else if (a == "--dirty") dirty = true;
    else if (a == "--no-velocity") noVelocity = true;
    else if (a == "--gmode" && i + 1 < args.size()) {
      const std::string m = args[++i];
      if (m == "nz") gMode = GMode::Nz;
      else if (m == "total") gMode = GMode::Total;
      else return usage();
    } else if (a == "--generate" && i + 1 < args.size()) {
      gen = true;
      scenario = args[++i];
    } else if (a == "--out" && i + 1 < args.size()) outPath = args[++i];
    else if (a == "--duration") { if (!value(duration)) return usage(); }
    else if (a == "--fps") { if (!value(fps) || fps < 1.0 || fps > 1000.0) return usage(); }
    else if (a == "--seed") { if (!value(seed) || seed < 0.0 || seed > 4294967295.0) return usage(); }
    else if (!a.empty() && a[0] != '-' && logPath.empty()) logPath = a;
    else return usage();
  }

  if (gen) {
    if (outPath.empty() || duration <= 0.0) return usage();
    return generate(scenario, duration, outPath, static_cast<std::uint32_t>(seed), dirty,
                    noVelocity, fps, cmdLine);
  }
  if (logPath.empty()) return usage();

  std::vector<CsvRow> rows;
  std::string err;
  if (!loadCsvLog(logPath, rows, &err)) {
    std::fprintf(stderr, "error: %s\n", err.c_str());
    return 2;
  }
  const ReplayResult result = replay(rows, gMode);
  const CheckLimits limits = readCheckDirectives(logPath);
  if (json) {
    const bool pass = !check || runCheck(result, limits, true);
    printJson(logPath, result, check, pass);
    return pass ? 0 : 1;
  }
  printText(logPath, result);
  return !check || runCheck(result, limits, false) ? 0 : 1;
}
