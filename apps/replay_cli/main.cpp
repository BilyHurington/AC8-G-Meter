// Replay + error analysis

struct CheckLimits {
  double gRms = kDefaultGRmsLimit;
  double gRms0 = kDefaultGRms0Limit;
  double aoaRms = kDefaultAoaRmsLimit;
  double latencyS = kMaxLatencyS;
};

// Reads "# check: key<=value ..." directives from comment lines.
CheckLimits readCheckDirectives(const std::string& path) {
  CheckLimits limits;
  std::ifstream file(path);
  std::string line;
  while (std::getline(file, line)) {
    const std::size_t pos = line.find("check:");
    if (line.empty() || line[0] != '#' || pos == std::string::npos) continue;
    std::string_view rest = std::string_view(line).substr(pos + 6);
    while (!rest.empty()) {
      const std::size_t sp = rest.find_first_of(" \t\r");
      const std::string token(rest.substr(0, sp));
      rest = sp == std::string_view::npos ? std::string_view{} : rest.substr(sp + 1);
      const std::size_t le = token.find("<=");
      double v = 0.0;
      if (le == std::string::npos || !parseDouble(token.c_str() + le + 2, v)) continue;
      const std::string key = token.substr(0, le);
      if (key == "g_rms") limits.gRms = v;
      else if (key == "g_rms0") limits.gRms0 = v;
      else if (key == "aoa_rms") limits.aoaRms = v;
      else if (key == "latency_ms") limits.latencyS = v / 1000.0;
    }
  }
  return limits;
}

struct Point {
  double t, estimate;
};
struct Series {
  std::vector<Point> est;                        // estimator output at accepted samples
  std::vector<std::pair<double, double>> truth;  // (t, true value), every distinct row
};

// Truth linearly interpolated at time t (series sorted by time).
double truthAt(const std::vector<std::pair<double, double>>& truth, double t) {
  auto it = std::lower_bound(truth.begin(), truth.end(), std::make_pair(t, -1e300));
  if (it == truth.begin()) return it->second;
  if (it == truth.end()) return truth.back().second;
  const auto& b = *it;
  const auto& a = *(it - 1);
  const double w = b.first > a.first ? (t - a.first) / (b.first - a.first) : 1.0;
  return a.second + (b.second - a.second) * w;
}

struct ErrorStats {
  std::size_t count = 0;
  double rms = 0.0, maxAbs = 0.0;     // estimate vs truth at the same instant
  double lagS = 0.0;                  // delay that best aligns estimate and truth
  double lagRms = 0.0, lagMaxAbs = 0.0;
};

ErrorStats errorAtLag(const Series& s, double lag) {
  ErrorStats e;
  double sumSq = 0.0;
  for (const Point& p : s.est) {
    const double err = p.estimate - truthAt(s.truth, p.t - lag);
    sumSq += err * err;
    e.maxAbs = std::max(e.maxAbs, std::abs(err));
  }
  e.count = s.est.size();
  e.rms = e.count ? std::sqrt(sumSq / static_cast<double>(e.count)) : 0.0;
  return e;
}

// Smoothing filters delay the estimate by design; report that delay separately from the
// error that remains once it is accounted for (the actual estimation quality).
ErrorStats analyze(const Series& s) {
  ErrorStats result = errorAtLag(s, 0.0);
  result.lagRms = result.rms;
  result.lagMaxAbs = result.maxAbs;
  for (double lag = kLagStepS; lag <= kMaxLagSearchS + 1e-9; lag += kLagStepS) {
    const ErrorStats e = errorAtLag(s, lag);
    if (e.rms < result.lagRms) {
      result.lagRms = e.rms;
      result.lagMaxAbs = e.maxAbs;
      result.lagS = lag;
    }
  }
  return result;
}

struct ReplayResult {
  std::size_t rows = 0;
  double logDurationS = 0.0;
  bool hasVelocity = false, hasTruthNz = false, hasTruthAoa = false;
  MetricsSnapshot snapshot;
  ErrorStats g, aoa;
};

ReplayResult replay(const std::vector<CsvRow>& rows, GMode gMode, const std::string& label) {
  PipelineConfig cfg;
  cfg.gMode = gMode;
  TelemetryPipeline pipeline(cfg);
  pipeline.setMissionLabel(label);

  ReplayResult r;
  r.rows = rows.size();
  if (!rows.empty()) r.logDurationS = rows.back().sample.t - rows.front().sample.t;

  Series gSeries, aoaSeries;
  double lastResetT = -1e300, lastCollectedT = -1e300;
  std::uint64_t resets = 0;
  MissionPhase prevPhase = MissionPhase::None;
  for (const CsvRow& row : rows) {
    const RawFlightSample& s = row.sample;
    r.hasVelocity |= s.velocity.has_value();
    r.hasTruthNz |= row.trueNz.has_value();
    r.hasTruthAoa |= row.trueAoaDeg.has_value();
    if (row.trueNz && (gSeries.truth.empty() || s.t > gSeries.truth.back().first))
      gSeries.truth.emplace_back(s.t, *row.trueNz);
    if (row.trueAoaDeg && (aoaSeries.truth.empty() || s.t > aoaSeries.truth.back().first))
      aoaSeries.truth.emplace_back(s.t, *row.trueAoaDeg);

    pipeline.push(s);
    const MetricsSnapshot snap = pipeline.snapshot();
    const std::uint64_t nowResets =
        snap.quality.resetsGap + snap.quality.resetsTeleport + snap.quality.resetsJump;
    if (nowResets != resets || (prevPhase == MissionPhase::Paused && s.phase != MissionPhase::Paused))
      lastResetT = s.t;
    resets = nowResets;
    prevPhase = s.phase;

    const FlightMetrics& m = snap.current;
    const bool fresh = m.valid && m.t == s.t && s.t > lastCollectedT &&
                       s.phase != MissionPhase::Paused && s.t - lastResetT >= kSettleAfterResetS;
    if (!fresh) continue;
    lastCollectedT = s.t;
    // In Total mode `g` is a magnitude; compare the body Nz component instead.
    if (row.trueNz) gSeries.est.push_back({s.t, gMode == GMode::Nz ? m.g : m.loadFactorBody.z});
    if (row.trueAoaDeg && m.aoaValid) aoaSeries.est.push_back({s.t, m.aoaDeg});
  }
  r.snapshot = pipeline.snapshot();
  if (!gSeries.est.empty()) r.g = analyze(gSeries);
  if (!aoaSeries.est.empty()) r.aoa = analyze(aoaSeries);
  return r;
}

const MissionStats& reportedStats(const ReplayResult& r) {
  return r.snapshot.lastReport ? r.snapshot.lastReport->stats : r.snapshot.mission;
}

void printText(const std::string& path, const ReplayResult& r) {
  const MissionStats& m = reportedStats(r);
  const DataQuality& q = r.snapshot.quality;
  std::printf("log      %s\n", path.c_str());
  std::printf("         %zu rows, %.2f s, velocity %s, truth %s\n", r.rows, r.logDurationS,
              r.hasVelocity ? "yes" : "no (from position)", r.hasTruthNz ? "yes" : "no");
  if (r.snapshot.lastReport)
    std::printf("mission  #%u%s, %.2f s flown\n", r.snapshot.lastReport->id,
                r.snapshot.lastReport->aborted ? " (aborted)" : "", m.durationS);
  else
    std::printf("mission  no completed mission (live stats), %.2f s flown\n", m.durationS);
  std::printf("  G      peak max %+.2f at %.1f s, min %+.2f at %.1f s\n", m.maxG, m.maxGAtS, m.minG,
              m.minGAtS);
  if (m.hasSustainedData)
    std::printf("         sustained max %+.2f at %.1f s, min %+.2f at %.1f s (excursions < %.2f s removed)\n",
                m.sustainedMaxG, m.sustainedMaxGAtS, m.sustainedMinG, m.sustainedMinGAtS,
                r.snapshot.lastReport ? r.snapshot.lastReport->minExcursionS : 0.0);
  else
    std::printf("         sustained --\n");
  std::printf("  onset  max %+.1f G/s, min %+.1f G/s\n", m.maxOnset, m.minOnset);
  std::printf("  AoA    max %.1f deg, max speed %.0f m/s\n", m.maxAoaDeg, m.maxSpeed);
  std::printf("  high-G %d episodes (sustained G), longest %.2f s, total %.2f s\n", m.highGEpisodes,
              m.longestHighGS, m.totalHighGS);
  if (r.snapshot.lastReport) {
    std::printf("  avg G  window: max (start) / min (start)\n");
    for (const WindowedG& w : r.snapshot.lastReport->windowed) {
      if (w.valid)
        std::printf("         %4.0f s: %+.2f (%.1f s) / %+.2f (%.1f s)\n", w.windowS, w.maxAvgG, w.maxAvgStartS,
                    w.minAvgG, w.minAvgStartS);
      else
        std::printf("         %4.0f s: -- (longer than the mission)\n", w.windowS);
    }
  }
  std::printf("  time in G bins:");
  for (double s : m.timeInGBinS) std::printf(" %.1f", s);
  std::printf(" s\n");
  std::printf("quality  accepted %llu (extreme G %llu), rejected: non-finite %llu, time %llu, "
              "spike %llu; resets: gap %llu, teleport %llu, jump %llu\n",
              static_cast<unsigned long long>(q.accepted),
              static_cast<unsigned long long>(q.extremeG),
              static_cast<unsigned long long>(q.rejectedNonFinite),
              static_cast<unsigned long long>(q.rejectedTime),
              static_cast<unsigned long long>(q.rejectedSpike),
              static_cast<unsigned long long>(q.resetsGap),
              static_cast<unsigned long long>(q.resetsTeleport),
              static_cast<unsigned long long>(q.resetsJump));
  const FilterState& f = r.snapshot.filter;
  if (f.input == FilterState::Input::PositionOnly)
    std::printf("filter   fixed at end: window %.1f ms, tau %.1f ms, onset %.0f ms (position-only input)\n",
                f.accelWindowS * 1000.0, f.smoothingTauS * 1000.0, f.onsetWindowS * 1000.0);
  else
    std::printf("filter   %s at end: window %.1f ms, tau %.1f ms, onset %.0f ms (input %.0f Hz, "
                "velocity noise %.4f m/s%s)\n",
                f.adaptive ? "adaptive" : "fixed", f.accelWindowS * 1000.0, f.smoothingTauS * 1000.0,
                f.onsetWindowS * 1000.0, f.sampleRateHz, f.velocityNoiseMS,
                f.noiseReady ? "" : ", measuring...");
  auto err = [](const char* name, const char* unit, const ErrorStats& e) {
    std::printf("  %-4s   n=%zu  zero-lag rms %.3f %s, max %.3f  |  aligned (lag %3.0f ms): rms %.3f, max %.3f\n",
                name, e.count, e.rms, unit, e.maxAbs, e.lagS * 1000.0, e.lagRms, e.lagMaxAbs);
  };
  if (r.hasTruthNz || r.hasTruthAoa) {
    std::printf("error vs truth (valid samples, %.1f s settle after resets)\n", kSettleAfterResetS);
    if (r.hasTruthNz) err("Nz", "G", r.g);
    if (r.hasTruthAoa) err("AoA", "deg", r.aoa);
  }
}

