// Generation

int generate(const std::string& scenarioArg, double duration, const std::string& outPath,
             std::uint32_t seed, bool dirty, bool noVelocity, double fps, const std::string& cmdLine) {
  SimulatedSourceOptions opt;
  if (scenarioArg == "level") opt.scenario = Scenario::LevelCruise;
  else if (scenarioArg == "turn") opt.scenario = Scenario::SustainedTurn;
  else if (scenarioArg == "pullpush") opt.scenario = Scenario::PullUpPushOver;
  else if (scenarioArg == "dogfight") opt.scenario = Scenario::DogfightMix;
  else {
    std::fprintf(stderr, "unknown scenario '%s'\n", scenarioArg.c_str());
    return 2;
  }
  if (duration < 2.0) {
    std::fprintf(stderr, "--duration must be >= 2 s\n");
    return 2;
  }
  opt.seed = seed;
  opt.frameRateHz = fps;
  opt.provideVelocity = !noVelocity;
  if (dirty) {
    opt.dirty.positionNoiseM = 0.02;
    opt.dirty.velocityNoiseMS = 0.05;
    opt.dirty.frameJitter = 0.35;
    opt.dirty.dropProbability = 0.03;
    opt.dirty.duplicateProbability = 0.02;
  }

  SimulatedSource sim(opt);
  std::vector<RawFlightSample> samples;
  std::vector<FlightState> truth;
  const double flight = duration - 1.0;  // last second: results screen (phase Ended)
  if (dirty) {
    // One of each glitch, spread over the flight.
    sim.generate(flight * 0.3, samples, &truth);
    sim.injectSpike();
    sim.generate(flight * 0.2, samples, &truth);
    sim.injectHitch(0.4);
    sim.generate(flight * 0.2, samples, &truth);
    sim.injectTeleport();
    sim.generate(flight * 0.3, samples, &truth);
  } else {
    sim.generate(flight, samples, &truth);
  }
  sim.endMission();
  sim.generate(1.0, samples, &truth);

  CsvRecorder rec;
  std::string err;
  if (!rec.open(outPath, &err)) {
    std::fprintf(stderr, "%s\n", err.c_str());
    return 2;
  }
  rec.writeComment("AC8 G-Meter flight log (simulated, with ground truth)");
  rec.writeComment("generated by: " + cmdLine);
  if (dirty) {
    rec.writeComment("dirty: noise, frame jitter, drops, duplicates, 1 spike, 1 hitch, 1 teleport");
    // Noise makes the adaptive filter choose a longer window (~90 ms delay at 60 Hz).
    rec.writeComment("check: g_rms<=0.35 g_rms0<=0.55 aoa_rms<=1.5 latency_ms<=110");
  } else if (noVelocity) {
    // Position-only input uses the fixed, longer accelWindowPositionOnlyS (~125 ms delay).
    rec.writeComment("check: g_rms0<=0.38 latency_ms<=145");
  }
  for (std::size_t i = 0; i < samples.size(); ++i)
    rec.write({samples[i], truth[i].trueNz, truth[i].trueAoaDeg});
  rec.close();
  std::printf("wrote %zu rows (%.1f s, %s) to %s\n", rec.rowsWritten(), duration,
              scenarioName(opt.scenario), outPath.c_str());
  return 0;
}

